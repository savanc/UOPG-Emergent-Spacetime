"""Emit Lean certificates lean/PositiveGeometryEmergentSpaceTime/HgDim2P{n}.lean for the permutohedron P_n = Cay(S_n, adjacent transpositions).
Vertices: permutations of 0..n-1 in one-line notation, lexicographic order (index 0 = identity).
Neighbour k of w is w with positions k, k+1 swapped (right multiplication by s_k).
For each label k the edge (e, s_k): optimal matching N[e] -> N[s_k] (BFS shortest walks) of cost n-2+2h,
and the inversion-indicator potential of notes/HG-DIM-2-permutohedron-proof-2026-10-31.md (defined in Lean, not emitted)."""
import itertools, sys
from collections import deque
from math import factorial

def emit(n):
    perms = list(itertools.permutations(range(n)))
    ix = {p: i for i, p in enumerate(perms)}
    def sw(p, k):
        q = list(p); q[k], q[k+1] = q[k+1], q[k]; return tuple(q)
    nbr = [[ix[sw(p, k)] for k in range(n-1)] for p in perms]
    def path(a, b):
        prev = {a: None}; dq = deque([a])
        while dq:
            u = dq.popleft()
            if u == b: break
            for v in nbr[u]:
                if v not in prev: prev[v] = u; dq.append(v)
        out = []; u = b
        while u != a: out.append(u); u = prev[u]
        return out[::-1]
    N = factorial(n); L = []
    L.append(f"""import PositiveGeometryEmergentSpaceTime.HgDim2

/-!
# HgDim2P{n} — Ollivier curvature certificates on the permutohedron graph P_{n} (HG-DIM-2, 2026-10-31)

`perms`: the {N} permutations of 0..{n-1} (one-line notation, lexicographic; index 0 is the identity).
`perms_valid`: each is a permutation of `List.range {n}`; `rank_P`: the Lehmer rank of `P i` is `i` (so `P` is injective,
`P_inj`, and the {N} = {n}! entries are all of S_{n}). `nbr_spec`: neighbour k of vertex i is `P i` with positions k, k+1
swapped (right multiplication by s_k), so `adj` is exactly the Cayley graph Cay(S_{n}, s_0..s_{n-2}).
For each label k, `edge{n}_k` certifies: lazy uniform measures on closed neighbourhoods (idleness 1/{n} = 1/(D+1)) of e and s_k
have minimum perfect-matching cost exactly n − 2 + 2h (h = hexagons on the edge), i.e. W1 = cost/{n} and
κ = (2 − 2h)/{n}. Upper bound: an explicit walk-realised matching. Lower bound: the integer 1-Lipschitz inversion
potential `PositiveGeometryEmergentSpaceTime.HgDim2.phiInv` (weak duality `PositiveGeometryEmergentSpaceTime.HgDim2.cost_lower`). Scope as in `PositiveGeometryEmergentSpaceTime.HgDim1`: the lower bound
is proved for matchings; fractional couplings reduce to matchings (Birkhoff, cited, not formalised).
Generated by sims/hgdim2/lean_emit.py.
-/

namespace PositiveGeometryEmergentSpaceTime.HgDim2P{n}
open PositiveGeometryEmergentSpaceTime.HgDim2

abbrev V := Fin {N}
def perms : List (List Nat) := [{", ".join("[" + ", ".join(map(str, p)) + "]" for p in perms)}]
def P (i : V) : List Nat := perms.getD i.val []
def nbrT : List (List Nat) := [{", ".join("[" + ", ".join(map(str, r)) + "]" for r in nbr)}]
def nbrs (i : V) : List V := (nbrT.getD i.val []).map fun j => (Fin.ofNat {N} j)
def adj (i j : V) : Bool := (nbrs i).contains j

theorem perms_length : perms.length = {N} := by decide +kernel
theorem perms_valid : ∀ i : V, (P i).length = {n} ∧ (List.range {n}).all (fun v => (P i).contains v) = true := by decide +kernel
theorem rank_P : ∀ i : V, lehmer (P i) = i.val := by decide +kernel
theorem P_inj (i j : V) (h : P i = P j) : i = j := Fin.ext (by rw [← rank_P i, ← rank_P j, h])
theorem nbr_spec : ∀ i : V, (nbrs i).length = {n-1} ∧ ∀ k : Fin {n-1}, P ((nbrs i).getD k.val 0) = swapAt (P i) k.val := by decide +kernel
""")
    for k in range(n-1):
        y = nbr[0][k]; h = (1 if k > 0 else 0) + (1 if k + 2 < n else 0); C = n - 2 + 2*h
        NA = [0] + nbr[0]; NB = [y] + nbr[y]
        ws = [(0, []), (y, [])]
        for j in range(n-1):
            if j == k: continue
            a = nbr[0][j]; b = nbr[y][j]; ws.append((a, path(a, b)))
        assert sum(len(t) for _, t in ws) == C, (n, k)
        wsS = ", ".join(f"({a}, [{', '.join(map(str, t))}])" for a, t in ws)
        L.append(f"""
/-! ### Label {k}: edge (e, s_{k}), h = {h}, cost {C}, κ = {2-2*h}/{n} -/
def NA_{k} : List V := [{", ".join(map(str, NA))}]
def NB_{k} : List V := [{", ".join(map(str, NB))}]
def ws_{k} : List (V × List V) := [{wsS}]
def phi_{k} (i : V) : Int := phiInv {n} {k} (P i)
theorem phi_{k}_lip : ∀ i : V, (nbrs i).all (fun j => decide (phi_{k} i - phi_{k} j ≤ 1)) = true := by decide +kernel
theorem phi_{k}_gap : (NA_{k}.map phi_{k}).sum - (NB_{k}.map phi_{k}).sum = {C} := by decide +kernel
theorem nbhd_{k} : NA_{k} = 0 :: nbrs 0 ∧ NB_{k} = {y} :: nbrs {y} ∧ (nbrs 0).getD {k} 0 = {y} := by decide +kernel
theorem ws_{k}_ok : (ws_{k}.all fun p => walkOk adj (p.1 :: p.2)) = true ∧ (ws_{k}.map Prod.fst).Perm NA_{k} ∧
    (ws_{k}.map fun p => fin p.1 p.2).Perm NB_{k} ∧ (ws_{k}.map fun p => (p.2.length : Int)).sum = {C} := by
  refine ⟨by decide +kernel, ?_, ?_, by decide +kernel⟩ <;> exact List.perm_iff_count.mpr (by decide +kernel)
theorem edge{n}_{k} : adj 0 {y} = true ∧ hexCount {n} {k} = {h} ∧
    (∃ ws : List (V × List V), (∀ p ∈ ws, walkOk adj (p.1 :: p.2) = true) ∧ (ws.map Prod.fst).Perm NA_{k} ∧
      (ws.map fun p => fin p.1 p.2).Perm NB_{k} ∧ (ws.map fun p => (p.2.length : Int)).sum = {C}) ∧
    (∀ ws : List (V × List V), (∀ p ∈ ws, walkOk adj (p.1 :: p.2) = true) → (ws.map Prod.fst).Perm NA_{k} →
      (ws.map fun p => fin p.1 p.2).Perm NB_{k} → {C} ≤ (ws.map fun p => (p.2.length : Int)).sum) := by
  obtain ⟨h1, h2, h3, h4⟩ := ws_{k}_ok
  refine ⟨by decide +kernel, by decide +kernel, ⟨ws_{k}, fun p hp => List.all_eq_true.mp h1 p hp, h2, h3, h4⟩, ?_⟩
  intro ws hw hA hB
  have hl : ∀ i j : V, adj i j = true → phi_{k} i - phi_{k} j ≤ 1 := by
    intro i j hij
    have := List.all_eq_true.mp (phi_{k}_lip i) j (by simpa [adj] using hij)
    simpa using this
  have := cost_lower adj phi_{k} hl ws hw
  rw [(hA.map phi_{k}).sum_eq, (hB.map phi_{k}).sum_eq, phi_{k}_gap] at this
  exact this
""")
    L.append(f"\nend PositiveGeometryEmergentSpaceTime.HgDim2P{n}\n")
    open(f"<local path>", "w").write("".join(L))

for n in map(int, sys.argv[1:]): emit(n)
