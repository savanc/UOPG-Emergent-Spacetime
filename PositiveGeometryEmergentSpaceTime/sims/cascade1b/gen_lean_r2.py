"""Generate lean/PositiveGeometryEmergentSpaceTime/Cascade1bR2.lean (CASCADE-1b r1 prereg §7 items 2-5) from the r2 run relations.
Post-run, reads cascade1b_r2_live.json only for the EM-n6 relations; re-derives offsets independently (eq. 2.4)."""
import itertools, json, re, sys, sympy as sp
n = 6
ch = [(a, b) for a in range(1, n + 1) for b in range(a + 2, n + 1) if not (a == 1 and b == n)]
cyc = lambda i: (i - 1) % n + 1
canon = lambda P: tuple(sorted(P))
mu = {P: sp.Symbol(f'mu{P[0]}{P[1]}') for P in ch}
m = {i: sp.Symbol(f'm{i}') for i in range(1, n + 1)}
def world(prefix, masses):
    X = {P: sp.Symbol(f'{prefix}{P[0]}{P[1]}') for P in ch}
    def Xv(i, j):
        i, j = cyc(i), cyc(j)
        if i == j: return sp.Integer(0)
        a, b = sorted((i, j))
        if b - a == 1: return masses[a]
        if (a, b) == (1, n): return masses[n]
        return X[(a, b)]
    c = lambda i, j: sp.expand(Xv(i, j) + Xv(i + 1, j + 1) - Xv(i, j + 1) - Xv(i + 1, j))
    return X, c
X, cX = world('X', m)
Y, cY = world('y', {i: sp.Integer(0) for i in range(1, n + 1)})
pairs = sorted({canon((i, j)) for i in range(1, n + 1) for j in range(1, n + 1) if (j - i) % n not in (0, 1, n - 1)})
sub = {X[P]: Y[P] + mu[P] for P in ch}
off = {ab: sp.expand(cX(*ab).subs(sub, simultaneous=True) - cY(*ab)) for ab in pairs}
assert all(not (o.free_symbols & set(Y.values())) for o in off.values())
src = sys.argv[1]
if src.endswith('.json'):
    rels = [sp.sympify(r) for r in json.load(open(src))['cells']['EM-n6']['S3_relations']]
else:  # checker stdout: the 'relations:' line after '--- EM-n6'
    L = open(src).read().split('\n'); i = [k for k, l in enumerate(L) if l.startswith('--- EM-n6')][0]
    rels = [sp.sympify(r) for r in re.findall(r"'([^']+)'", L[i + 1])]
theta = [mu[P] for P in ch] + [m[i] for i in range(1, n + 1)]
M1 = sp.Matrix([[sp.diff(off[ab], t) for t in theta] for ab in pairs])
M2 = sp.Matrix([[sp.diff(r, t) for t in theta] for r in rels])
assert M1.rank() == M2.rank() == sp.Matrix.vstack(M1, M2).rank() == 9, 'relations != offsets span'

L = lambda e: str(sp.expand(e)).replace('**', '^')
yv = [Y[P] for P in ch]; xv = [X[P] for P in ch]; muv = [mu[P] for P in ch]; mv = [m[i] for i in range(1, n + 1)]
def tri6(vals):
    tot = []
    for S in itertools.combinations(ch, 3):
        if all(not ((P[0] < Q[0] < P[1] < Q[1]) or (Q[0] < P[0] < Q[1] < P[1])) for P, Q in itertools.combinations(S, 2)):
            tot.append(S)
    assert len(tot) == 14
    return tot
TRI = tri6(None)
names = lambda vs: ' '.join(str(v) for v in vs)
out = []
w = out.append
w('/-')
w('CASCADE-1b r2 (prereg/CASCADE-1b-r2-fast-VD-2026-10-24.md §6; items 2-5 of prereg/CASCADE-1b-split-fix-blind-retest-2026-10-23.md §7).')
w('Generated by sims/cascade1b/gen_lean_r2.py from the EM-n6 S3 relations of run CASCADE1b-2026-10-24-r2.')
w('Offsets re-derived independently from eq. 2.4 of arXiv 2312.16282 (X_{i,i+1} = m_i).')
w('Re-wordings (declared in the result review): items 3 and 4 are proved for the massless amplitude in y = X − μ')
w('coordinates plus the linear transport lemma; eq. 3.7 is stated as an explicit factorisation (the checker tests the')
w('equivalent rank-1 condition).')
w('-/')
w('import Mathlib\n\nnamespace PositiveGeometryEmergentSpaceTime.Cascade1bR2\n')
w('/-- The 14-term massless n = 6 triangulation sum (eq. 3.6) in y coordinates. -/')
w(f'def A6 ({names(yv)} : ℚ) : ℚ :=')
w('  ' + ' + '.join('1 / (' + ' * '.join(str(Y[P]) for P in S) + ')' for S in TRI))
w('')
w(f'/-- The nine EM offsets o_ab(μ, m) = c_ab(X) − c_ab(y) with X = y + μ, pairs {pairs}. -/')
w(f'def offsetsEM ({names(muv)} {names(mv)} : ℚ) : List ℚ :=')
w('  [' + ', '.join(L(off[ab]) for ab in pairs) + ']')
w('')
w('/-- The EM-n6 S3 relations printed by run CASCADE1b-2026-10-24-r2. -/')
w(f'def relsEM ({names(muv)} {names(mv)} : ℚ) : List ℚ :=')
w('  [' + ', '.join(L(r) for r in rels) + ']')
w('')
simpl = 'simp only [offsetsEM, relsEM, List.mem_cons, List.mem_nil_iff, or_false, forall_eq_or_imp, forall_eq]'
w('/-- §7 item 2: all nine EM offsets vanish iff the live relations hold. -/')
w(f'theorem em_n6_offsets_zero_iff ({names(muv)} {names(mv)} : ℚ) :')
w(f'    (∀ o ∈ offsetsEM {names(muv)} {names(mv)}, o = 0) ↔ (∀ r ∈ relsEM {names(muv)} {names(mv)}, r = 0) := by')
w(f'  {simpl}')
w('  constructor')
w('  · rintro ⟨' + ', '.join(f'h{k}' for k in range(9)) + '⟩')
w('    refine ⟨' + ', '.join('?_' for _ in range(9)) + '⟩ <;> linarith')
w('  · rintro ⟨' + ', '.join(f'h{k}' for k in range(9)) + '⟩')
w('    refine ⟨' + ', '.join('?_' for _ in range(9)) + '⟩ <;> linarith')
w('')
# item 3: diamonds
def solve_for(eqs, cands):
    for S in itertools.combinations(cands, len(eqs)):
        try:
            sol = sp.solve(eqs, S, dict=True)
        except Exception:
            continue
        if sol and len(sol[0]) == len(S):
            return S, sol[0]
    raise RuntimeError
DIAM = {'skinny': [(1, 3), (1, 4), (1, 5)], 'square': [(1, 4), (1, 5), (2, 4), (2, 5)]}
for nm, prs in DIAM.items():
    eqs = [cY(*ab) for ab in prs]
    S, sol = solve_for(eqs, yv)
    A = sum(sp.Mul(*[1 / Y[P] for P in T]) for T in TRI)
    assert sp.simplify(A.subs(sol)) == 0, nm
    w(f'/-- Massless zero (CITED 2312.16282 §3, reproduced): A6 vanishes on the {nm} diamond locus c_ab = 0, ab ∈ {prs}. -/')
    w(f'theorem a6_zero_{nm} ({names(yv)} : ℚ)')
    for k, ab in enumerate(prs):
        w(f'    (hc{k} : {L(cY(*ab))} = 0)')
    w('    ' + ' '.join(f'(h{P[0]}{P[1]} : {Y[P]} ≠ 0)' for P in ch) + f' :\n    A6 {names(yv)} = 0 := by')
    for v in S:
        w(f'  have e{v} : {v} = {L(sol[v])} := by linarith')
    w('  subst ' + ' '.join(f'e{v}' for v in S))
    w('  unfold A6\n  field_simp\n  ring')
    w('')
    # massive transport version
    w(f'/-- §7 item 3 ({nm}): on the live relations, the massive EM family A6(X − μ) vanishes on the physical {nm} diamond locus. -/')
    w(f'theorem zeros6_of_rel_{nm} ({names(xv)} {names(muv)} {names(mv)} : ℚ)')
    w(f'    (hr : ∀ r ∈ relsEM {names(muv)} {names(mv)}, r = 0)')
    for k, ab in enumerate(prs):
        w(f'    (hc{k} : {L(cX(*ab))} = 0)')
    w('    ' + ' '.join(f'(h{P[0]}{P[1]} : {X[P]} - {mu[P]} ≠ 0)' for P in ch) + ' :')
    w('    A6 ' + ' '.join(f'({X[P]} - {mu[P]})' for P in ch) + ' = 0 := by')
    w(f'  have ho := (em_n6_offsets_zero_iff {names(muv)} {names(mv)}).2 hr')
    w('  simp only [offsetsEM, List.mem_cons, List.mem_nil_iff, or_false, forall_eq_or_imp, forall_eq] at ho')
    w('  obtain ⟨' + ', '.join(f'o{k}' for k in range(9)) + '⟩ := ho')
    w(f'  apply a6_zero_{nm}')
    w('  all_goals first | assumption | linarith')
    w('')
# item 4: eq. 3.7 factorisations (rotation 0)
EQ37 = [([(1, 3), (1, 5)], [[(1, 3), (2, 6)], [(2, 4), (1, 5), (3, 5), (3, 6), (4, 6)]], [(1, 4), (2, 5)]),
        ([(1, 4), (1, 5), (2, 5)], [[(1, 4), (3, 6)], [(1, 3), (2, 6)], [(1, 5), (4, 6)]], [(2, 4), (2, 5), (3, 5)])]
A = sum(sp.Mul(*[1 / Y[P] for P in T]) for T in TRI)
for li, (zp, groups, el) in enumerate(EQ37, 1):
    eqs = [cY(*ab) for ab in zp]
    sol = sp.solve(eqs, [Y[P] for P in el], dict=True)[0]
    Ar = sp.factor(sp.together(A.subs(sol)))
    num, den = sp.fraction(Ar)
    fs = []
    for g in groups:
        gv = {Y[P] for P in g}
        part = sp.Integer(1)
        for f, e in sp.factor_list(num)[1]:
            if f.free_symbols and f.free_symbols <= gv: part *= f ** e
        for f, e in sp.factor_list(den)[1]:
            if f.free_symbols and f.free_symbols <= gv: part /= f ** e
        fs.append(part)
    const = sp.factor_list(num)[0] / sp.factor_list(den)[0]
    assert sp.simplify(Ar - const * sp.Mul(*fs)) == 0, f'line {li} not separable'
    free = [v for v in yv if v not in sol]
    dens = sorted({str(sp.expand(f)) for T in TRI for f in [Y[P].subs(sol) for P in T]})
    hyps = ' '.join(f'(hd{k} : {d.replace("**", "^")} ≠ 0)' for k, d in enumerate(dens))
    w(f'/-- §7 item 4, eq. 3.7 line {li} (rotation 0; CITED 2312.16282 eq. 3.7, reproduced): on c = 0 at {zp}, eliminating {el},')
    w(f'A6 factorises over the groups {groups}. -/')
    w(f'theorem eq37_line{li} ({names(free)} : ℚ) {hyps} :')
    args = ' '.join(f'({L(sol[v])})' if v in sol else str(v) for v in yv)
    w(f'    A6 {args} = ({const}) * ' + ' * '.join(f'({str(f).replace("**", "^")})' for f in fs) + ' := by')
    w('  unfold A6\n  field_simp\n  ring')
    w('')
    if li == 1:
        tr_ab = zp
# transport for item 4
w('/-- §7 item 4 transport: c_ab(X) = c_ab(X − μ) + o_ab(μ, m) for every non-adjacent pair, so on the relations the')
w('physical locus of the massive family is the massless locus in y = X − μ (and eq. 3.7 transports). -/')
w(f'theorem c_transport ({names(xv)} {names(muv)} {names(mv)} : ℚ) :')
cYsub = {Y[P]: X[P] - mu[P] for P in ch}
w('    ' + ' ∧\n    '.join(f'{L(cX(*ab))} = ({L(cY(*ab).subs(cYsub, simultaneous=True))}) + ({L(off[ab])})' for ab in pairs) + ' := by')
w('  refine ⟨' + ', '.join('?_' for _ in pairs) + '⟩ <;> ring')
w('')
# item 5
w('/-- §7 item 5: the uniform point m_i = μ_P = M satisfies the live relations (that it is S4-interior for M > 0 is SIMULATED, not proved here). -/')
w('theorem uniform_interior (M : ℚ) : ∀ r ∈ relsEM ' + ' '.join('M' for _ in muv + mv) + ', r = 0 := by')
w('  simp only [relsEM, List.mem_cons, List.mem_nil_iff, or_false, forall_eq_or_imp, forall_eq]')
w('  refine ⟨' + ', '.join('?_' for _ in rels) + '⟩ <;> ring')
w('\nend PositiveGeometryEmergentSpaceTime.Cascade1bR2')
