L = lambda xs: '[' + ', '.join(str(x) for x in xs) + ']'
def walks(c): return '[' + ', '.join(f'({w[0]}, {L(w[1:])})' for w in c['walks']) + ']'
def block(tag, c, cost):
    return f'''
/-- Closed neighbourhoods of the {tag} edge ({c['x']}, {c['y']}) (p = {c['p']}). -/
def NA_{tag} : List V := {L(c['A'])}
/-- See `NA_{tag}`. -/
def NB_{tag} : List V := {L(c['B'])}
/-- Integer 1-Lipschitz Kantorovich potential for the {tag} edge. -/
def phi_{tag} : V → Int := fun i => ({L(c['phi'])} : List Int).getD i.val 0
/-- An optimal matching N[x] → N[y], realised by shortest walks (start, rest). -/
def ws_{tag} : List (V × List V) := {walks(c)}

theorem phi_{tag}_lip : ∀ i j : V, adj i j = true → phi_{tag} i - phi_{tag} j ≤ 1 := by decide +kernel
theorem phi_{tag}_gap : (NA_{tag}.map phi_{tag}).sum - (NB_{tag}.map phi_{tag}).sum = {cost} := by decide +kernel
theorem ws_{tag}_ok : (ws_{tag}.all fun p => walkOk (p.1 :: p.2)) = true ∧ (ws_{tag}.map Prod.fst).Perm NA_{tag} ∧
    (ws_{tag}.map fun p => fin p.1 p.2).Perm NB_{tag} ∧ (ws_{tag}.map fun p => (p.2.length : Int)).sum = {cost} := by
  refine ⟨by decide +kernel, ?_, ?_, by decide +kernel⟩ <;> exact List.perm_iff_count.mpr (by decide +kernel)

/-- The {tag} edge: adjacent, quadrilateral with p = {c['p']} diagonal sides, and minimum matching cost exactly {cost}
over closed neighbourhoods of size 5 (so W1 = {cost}/5 and κ = 1 − {cost}/5). -/
theorem edge_{tag} : adj {c['x']} {c['y']} = true ∧ pSides (T {c['x']}) (T {c['y']}) = {c['p']} ∧
    (∃ ws : List (V × List V), (∀ p ∈ ws, walkOk (p.1 :: p.2) = true) ∧ (ws.map Prod.fst).Perm NA_{tag} ∧
      (ws.map fun p => fin p.1 p.2).Perm NB_{tag} ∧ (ws.map fun p => (p.2.length : Int)).sum = {cost}) ∧
    (∀ ws : List (V × List V), (∀ p ∈ ws, walkOk (p.1 :: p.2) = true) → (ws.map Prod.fst).Perm NA_{tag} →
      (ws.map fun p => fin p.1 p.2).Perm NB_{tag} → {cost} ≤ (ws.map fun p => (p.2.length : Int)).sum) := by
  obtain ⟨h1, h2, h3, h4⟩ := ws_{tag}_ok
  refine ⟨by decide +kernel, by decide +kernel, ⟨ws_{tag}, fun p hp => List.all_eq_true.mp h1 p hp, h2, h3, h4⟩, ?_⟩
  intro ws hw hA hB
  have := cost_lower phi_{tag} phi_{tag}_lip ws hw
  rw [(hA.map phi_{tag}).sum_eq, (hB.map phi_{tag}).sum_eq, phi_{tag}_gap] at this
  exact this

/-- κ(e) = 1 − W1 with W1 = cost/(D+1), D + 1 = 5; equals (2 − p)/5. -/
theorem kappa_{tag} : (1 : ℚ) - {cost}/5 = (2 - {c['p']})/5 := by norm_num
'''
hdr = f'''import Mathlib.Data.Rat.Defs
import Mathlib.Algebra.BigOperators.Group.List.Basic
import Mathlib.Tactic.Linarith
import Mathlib.Tactic.NormNum

/-!
# HgDim1 — Ollivier curvature certificates on the associahedron flip graph K_7 (HG-DIM-1, 2026-10-31)

Vertices: the 42 triangulations of a convex 7-gon, as bitmasks over its 14 diagonals (`diagA`, `diagB`).
Two triangulations are adjacent (one flip) iff their masks differ in exactly two bits (`adj`); `tris_valid`
checks every mask is 4 pairwise noncrossing diagonals, `tris_distinct` and `regular4` that the graph is 4-regular.
For uniform measures on closed neighbourhoods (idleness 1/(D+1), D = 4), W1 is the minimum perfect-matching cost / 5
(equal uniform masses). `cost_lower` is weak duality: any 1-Lipschitz potential bounds every walk-realised matching.
`edge_neg`: a flip whose quadrilateral has p = 3 diagonal sides has matching cost exactly 6, κ = −1/5.
`edge_pos`: a flip with p = 1 has cost exactly 4, κ = 1/5. Both match κ = (2 − p)/(D+1) (HG-DIM-1 verdict LOCAL-COUNT).
Scope: the lower bound is proved for matchings; the fractional-coupling bound follows by the same potential
(Kantorovich duality, cited, not formalised). Data generated by sims/hgdim1/lean_cert_gen.py.
-/

namespace PositiveGeometryEmergentSpaceTime.HgDim1

/-- Vertex index of K_7. -/
abbrev V := Fin 42
/-- Diagonal endpoints of the 7-gon (index k ↦ (diagA k, diagB k)). -/
def diagA : List Nat := {L([a for a, b in d['diags']])}
/-- See `diagA`. -/
def diagB : List Nat := {L([b for a, b in d['diags']])}
/-- The 42 triangulations as diagonal bitmasks. -/
def tris : List Nat := {L(d['mask'])}
/-- Mask of vertex i. -/
def T (i : V) : Nat := tris.getD i.val 0
/-- Number of set bits among the 14 diagonal bits. -/
def bits (m : Nat) : Nat := ((List.range 14).filter fun k => m.testBit k).length
/-- Flip adjacency. -/
def adj (i j : V) : Bool := bits (T i ^^^ T j) == 2
/-- Strict crossing of diagonals k and l. -/
def crosses (k l : Nat) : Bool :=
  let a := diagA.getD k 0; let b := diagB.getD k 0; let c := diagA.getD l 0; let e := diagB.getD l 0
  (decide (a < c) && decide (c < b) && decide (b < e)) || (decide (c < a) && decide (a < e) && decide (e < b))
/-- Every mask has 4 diagonals, pairwise noncrossing. -/
theorem tris_valid : ∀ i : V, bits (T i) = 4 ∧ ∀ k < 14, ∀ l < 14, (T i).testBit k → (T i).testBit l → crosses k l = false := by
  decide +kernel
theorem tris_distinct : ∀ i j : V, T i = T j → i = j := by decide +kernel
theorem regular4 : ∀ i : V, ((List.finRange 42).filter fun j => adj i j).length = 4 := by decide +kernel

/-- Polygon-side test in the 7-gon: u < v is a diagonal iff v − u ≥ 2 and (u, v) ≠ (0, 6). -/
def isDiag (u v : Nat) : Bool := decide (v ≥ u + 2) && !(u == 0 && v == 6)
/-- The unique diagonal index set in `m` but not in `m'`. -/
def firstOnly (m m' : Nat) : Nat := ((List.range 14).filter fun k => m.testBit k && !m'.testBit k).headD 0
/-- p: number of sides of the flip quadrilateral that are diagonals. The flipped diagonals k, l are the two
diagonals of the quadrilateral, so its four sides are exactly the four (endpoint of k, endpoint of l) pairs. -/
def pSides (m m' : Nat) : Nat :=
  let k := firstOnly m m'; let l := firstOnly m' m
  let a := diagA.getD k 0; let c := diagB.getD k 0; let b := diagA.getD l 0; let e := diagB.getD l 0
  let s := fun u v => isDiag (min u v) (max u v)
  [s a b, s a e, s c b, s c e].count true

/-- Walk check: consecutive vertices adjacent. -/
def walkOk : List V → Bool
  | [] => false
  | [_] => true
  | a :: b :: t => adj a b && walkOk (b :: t)
/-- End vertex of the walk a :: t. -/
def fin (a : V) (t : List V) : V := (a :: t).getLast (List.cons_ne_nil a t)

theorem lip_walk (φ : V → Int) (hφ : ∀ i j : V, adj i j = true → φ i - φ j ≤ 1) :
    ∀ (t : List V) (a : V), walkOk (a :: t) = true → φ a - φ (fin a t) ≤ t.length := by
  intro t
  induction t with
  | nil => intro a _; simp [fin]
  | cons b t ih =>
    intro a h
    simp only [walkOk, Bool.and_eq_true] at h
    have h1 := hφ a b h.1
    have h2 := ih b h.2
    have hf : fin a (b :: t) = fin b t := by simp [fin]
    rw [hf]; simp only [List.length_cons, Nat.cast_add, Nat.cast_one]; linarith

/-- Weak duality for walk-realised matchings. -/
theorem cost_lower (φ : V → Int) (hφ : ∀ i j : V, adj i j = true → φ i - φ j ≤ 1) :
    ∀ ws : List (V × List V), (∀ p ∈ ws, walkOk (p.1 :: p.2) = true) →
      ((ws.map Prod.fst).map φ).sum - ((ws.map fun p => fin p.1 p.2).map φ).sum ≤ (ws.map fun p => (p.2.length : Int)).sum := by
  intro ws
  induction ws with
  | nil => intro _; simp
  | cons p ws ih =>
    intro hw
    have h1 := lip_walk φ hφ p.2 p.1 (hw p (List.mem_cons_self))
    have h2 := ih (fun q hq => hw q (List.mem_cons_of_mem p hq))
    simp only [List.map_cons, List.sum_cons]; linarith
'''
