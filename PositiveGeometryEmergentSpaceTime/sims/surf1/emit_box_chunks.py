#!/usr/bin/env python3
"""SURF-1' (data only): turn the Lean #eval output of lean_gen/BoxGen.lean (per-orientation coefficient vectors
of W(tree4_u o box1234) on the full exponent window) into kernel-checked chunk modules
lean/PositiveGeometryEmergentSpaceTime/Surf1/Box/C{0..3}.lean.  The kernel re-derives every vector by `decide +kernel`; this script only
supplies the expected values.  No scoring, no gates."""
import ast, pathlib, re
HERE = pathlib.Path(__file__).resolve().parent
txt = (HERE / 'lean_gen' / 'boxgen_eval_out.txt').read_text().strip().split('\n')
blocks, cur = [], ''
for line in txt:
    if line.startswith('[') and cur and cur.count('[') == cur.count(']'):
        blocks.append(cur); cur = ''
    cur += line
blocks.append(cur)
assert len(blocks) == 3, len(blocks)
vecs = ast.literal_eval(blocks[2])
assert len(vecs) == 64 and all(len(v) == 46 for v in vecs)
out = HERE.parent.parent / 'lean' / 'PositiveGeometryEmergentSpaceTime' / 'Surf1' / 'Box'
out.mkdir(parents=True, exist_ok=True)
HDR = ['/-', 'Copyright (c) 2026 Savan Chhaniyara. All rights reserved.',
       'Released under MIT license as described in the file LICENSE.', 'Authors: Savan Chhaniyara', '-/']


def wrap_vec(v, ind='    ', width=100):
    """Render a Python int list as a Lean list literal, wrapped to `width` columns."""
    lines, cur = [], ind + '['
    for i, x in enumerate(v):
        tok = str(x) + (', ' if i < len(v) - 1 else ']')
        if len(cur) + len(tok.rstrip()) > width:
            lines.append(cur.rstrip()); cur = ind + ' '
        cur += tok
    lines.append(cur + ' := by')
    return lines


for c in range(4):
    lo, hi = 16 * c, 16 * c + 15
    L = HDR + ['import PositiveGeometryEmergentSpaceTime.Surf1.Box.Graph', '', '/-!',
               f"# SURF-1' box chunk {c}", '',
               '## i. Overview', '',
               f'Expected coefficient vectors of the colour weight W(tree4_u o box1234) at c = 1',
               f'for orientation patterns o = {lo}..{hi}, on the exponent window 36..-9',
               '(46 entries). Generated by sims/surf1/emit_box_chunks.py from a Lean #eval;',
               'the kernel re-derives every vector by `decide +kernel`.', '',
               '## ii. Key results', '',
               f'- `boxU_o{lo}` .. `boxU_o{hi}`: `ovec boxU o 36 46` equals the listed vector.', '',
               '## iii. Table of contents', '',
               '- One theorem per orientation pattern, in order.', '',
               '## iv. References', '',
               "- The SURF-1' preregistration and result review in this repository.", '-/', '',
               'set_option autoImplicit false', '', 'namespace PositiveGeometryEmergentSpaceTime.Surf1', '']
    for o in range(lo, hi + 1):
        L.append(f'/-- Coefficient vector `ovec boxU {o} 36 46` for orientation pattern {o} (generated by')
        L.append('  sims/surf1/emit_box_chunks.py; checked by `decide +kernel`). -/')
        L.append(f'theorem boxU_o{o} : ovec boxU {o} 36 46 =')
        L += wrap_vec(vecs[o])
        L.append('  decide +kernel')
        L.append('')
    L.append('end PositiveGeometryEmergentSpaceTime.Surf1')
    (out / f'C{c}.lean').write_text('\n'.join(L) + '\n')
tot = [sum(v[i] for v in vecs) for i in range(46)]
print('total', [(36 - i, t) for i, t in enumerate(tot) if t])
