"""LEAN-CERT-2 Lean emitter (post-prereg data formatting only; no checking logic).
Writes Lean list literals (rows plus transposes) for the certificates produced by the locked
`leancert2_checker.py`: live FR-WZW certificates are parsed from `certs_lean.txt`; the planted ABHY and
PL2 certificates and the forged B1 certificate are regenerated by the locked `certify` (deterministic).
Usage: python3 sims/leancert2/emit_lean.py OUT.lean [--pl2]"""
import ast, re, sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
import leancert2_checker as C

def L(rows):
    return "[" + ",\n  ".join("[" + ", ".join(str(x) for x in r) + "]" for r in rows) + "]"

def T(rows, ncols):
    return [[r[j] for r in rows] for j in range(ncols)]

def emit(name, Mr, Kr, Pr, Qr, d, m, n, k):
    Mc, Kc, Qc = T(Mr, n), T(Kr, k), T(Qr, n)
    out = [f"-- {name}: m = {m}, n = {n}, k = {k}"]
    for suf, val in (("Mr", Mr), ("Mc", Mc), ("Kr", Kr), ("Kc", Kc), ("Pr", Pr), ("Qr", Qr), ("Qc", Qc)):
        out.append(f"def {name}_{suf} : List (List ℤ) := {L(val)}")
    out.append(f"def {name}_d : ℤ := {d}")
    return "\n".join(out) + "\n"

def from_cert(name, c):
    return emit(name, c['Mr'], c['Kr'], c['Pr'], c['Qr'], c['d'], c['m'], c['n'], c['k'])

def parse_certs(path):
    txt = Path(path).read_text()
    blocks = {}
    for mm in re.finditer(r"def (\w+)_(M|K|P|Q) : List \(List ℤ\) := (\[.*?\])\n(?=def|-- )", txt, re.S):
        blocks.setdefault(mm.group(1), {})[mm.group(2)] = ast.literal_eval(mm.group(3))
    for mm in re.finditer(r"def (\w+)_d : ℤ := (-?\d+)", txt):
        blocks[mm.group(1)]['d'] = int(mm.group(2))
    for mm in re.finditer(r"-- (\w+): m = (\d+), n = (\d+), rank = (\d+), k = (\d+)", txt):
        b = blocks[mm.group(1)]; b['m'], b['n'], b['k'] = int(mm.group(2)), int(mm.group(3)), int(mm.group(5))
    return blocks

if __name__ == '__main__':
    out = Path(sys.argv[1]); parts = []
    for n in (5, 6, 7):
        parts.append(from_cert(f"abhyL{n}", C.certify(C.abhy_eq5(n))))
    c = C.certify(C.abhy_eq5(6)); n6, d6 = c['n'], c['d']
    Kr = [row + [d6 if i == 0 else 0] for i, row in enumerate(c['Kr'])]
    Qr = c['Qr'] + [[1 if j == 0 else 0 for j in range(n6)]]
    parts.append(emit("brokenB1", c['Mr'], Kr, c['Pr'], Qr, d6, c['m'], n6, c['k'] + 1))
    if '--pl2' in sys.argv:
        parts.append(from_cert("plantedPL2", C.certify(C.synthetic(120, 56, 46, 1))))
    certs = C.OUTDIR / 'certs_lean.txt'
    if certs.exists():
        for name, b in parse_certs(certs).items():
            parts.append(emit(name, b['M'], b['K'], b['P'], b['Q'], b['d'], b['m'], b['n'], b['k']))
    out.write_text("\n".join(parts))
    print(f"wrote {out}: {len(parts)} certificates, {out.stat().st_size} bytes")
