"""Build the blueprint outputs from out/claims.json + verdicts.py + defs_glossary.py.

Writes notes/alignment/{blueprint.tsv, BLUEPRINT-ALL.md, GLOSSARY.md} and tools/alignment/out/BlueprintCheck.lean
(one batched #check / #print axioms file; run once with `cd lean && lake env lean ../tools/alignment/out/BlueprintCheck.lean`).
"""
import json, re, pathlib, collections
from verdicts import V
from defs_glossary import DEFS, G
import glossary_terms
ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / "tools/alignment/out"; NOTES = ROOT / "notes/alignment"
C = json.load(open(OUT / "claims.json"))["claims"]
I = json.load(open(OUT / "lean_index.json"))
PAPER_LINES = {k: (ROOT / p).read_text().splitlines() for k, p in glossary_terms.PAPERS.items()}
BYMOD = collections.defaultdict(list)
for k, v in I.items(): BYMOD[v["module"]].append(k)

def exact_line(c):
    """Line in the paper where the claim's last sentence actually sits (claims.json gives the block start)."""
    L = PAPER_LINES[c["paper"]]; tail = c["text"].strip()[-60:]
    for i in range(max(0, c["line"] - 1), min(len(L), c["line"] + 40)):
        if tail[-40:] in L[i]: return i + 1
    return c["line"]

def expand(d):
    if d.startswith("mod:"):
        m = "PositiveGeometryEmergentSpaceTime." + d[4:]
        names = sorted(n for mm, ns in BYMOD.items() if mm == m or mm.startswith(m + ".") for n in ns
                       if I[n]["kind"] in ("theorem", "lemma", "thm"))
        return names
    return ["PositiveGeometryEmergentSpaceTime." + d]

def sig(n, maxlen=600):
    v = I.get(n)
    return re.sub(r"\s+", " ", v["sig"])[:maxlen] if v else "?? NOT IN INDEX"

def def_literal(n, maxlines=8):
    v = I[n]; L = (ROOT / "lean" / v["file"]).read_text().splitlines()
    out = []
    for l in L[v["line"] - 1:v["line"] - 1 + maxlines]:
        if out and (l.startswith("/--") or l.strip() == "" or re.match(r"(theorem|lemma|def|noncomputable|@\[)", l)): break
        out.append(l.strip())
    s = " ".join(out); return s[:500] + (" …" if len(s) > 500 else "")

def esc(s): return (s or "").replace("\t", " ").replace("\n", " ")

rows = []
for i, c in enumerate(C):
    v = V.get(i, dict(t="META"))
    rung = v.get("rung", c["rung"])
    decls = [n for d in v.get("d", []) for n in expand(d)]
    lit = " ;; ".join(f"{n.removeprefix('PositiveGeometryEmergentSpaceTime.')}: {sig(n, 400)}" for n in decls if not v.get("d", [""])[0].startswith("mod:") or len(decls) <= 3)
    if any(d.startswith("mod:") for d in v.get("d", [])):
        mods = [d[4:] for d in v["d"] if d.startswith("mod:")]
        lit = (lit + " ;; " if lit else "") + "modules " + ", ".join(f"{m} ({len(expand('mod:'+m))} thm)" for m in mods)
    rows.append(dict(id=i, rung=rung, loc=f"{c['paper']}:{exact_line(c)}", type=v["t"], prose=esc(c["text"].strip()[-400:]),
                     decls=decls, lit=esc(lit), hid=esc(v.get("hid", "")), verdict=v.get("v", ""), note=esc(v.get("n", "")), rw=esc(v.get("rw", ""))))
for name, rung, verdict, note in DEFS:
    n = "PositiveGeometryEmergentSpaceTime." + name
    rows.append(dict(id=f"D{len(rows)}", rung=rung, loc=f"lean/{I[n]['file']}:{I[n]['line']}", type="DEF", prose="", decls=[n],
                     lit=esc(def_literal(n)), hid="", verdict=verdict, note=esc(note), rw=""))

NOTES.mkdir(parents=True, exist_ok=True)
cols = ["id", "rung", "loc", "type", "verdict", "prose", "decls", "lit", "hid", "note", "rw"]
with open(NOTES / "blueprint.tsv", "w") as f:
    f.write("\t".join(["id", "rung", "paper:line", "row_type", "verdict", "prose (tail)", "lean_decls", "literal_statement", "hidden_hypotheses", "note", "proposed_rewording"]) + "\n")
    for r in rows:
        f.write("\t".join(esc(", ".join(x.removeprefix("PositiveGeometryEmergentSpaceTime.") for x in r[k])) if k == "decls" else str(r[k]) for k in cols) + "\n")

# ---------- BLUEPRINT-ALL.md
JUDGED = ("CLAIM", "LISTING", "SCOPE", "DEF")
cnt = collections.Counter((r["type"], r["verdict"]) for r in rows)
byrung = collections.defaultdict(list)
for r in rows: byrung[r["rung"]].append(r)
md = ["# Blueprint rows: prose vs Lean, every rung with a Lean claim (2026-11-03)", "",
      "Generated by `tools/alignment/build.py` from `out/claims.json` (extract.py), `verdicts.py` and `defs_glossary.py`.",
      "Row types: CLAIM (prose claim tagged PROVED / \\lean / 'Lean proves'), LISTING (printed Lean listing), SCOPE (a sentence saying what Lean does *not* cover; MATCH = accurate),",
      "DEF (a definition a headline theorem depends on), PAPER (paper proof only, not judged), META (no checkable Lean claim, not judged).",
      "Verdicts: MATCH, OVERSTATES, UNDERSTATES, MISSING-LEAN, NAME-ONLY. Paper keys: I = methods paper, II = evidence paper, C = curvature paper.",
      "Pilot rows (SURF-1′, HG-DIM-1 mean, RG-IR-1) reuse `PILOT-2026-10-31.md`.", "",
      "| row type | MATCH | OVERSTATES | UNDERSTATES | MISSING-LEAN | NAME-ONLY | unjudged |", "|---|---|---|---|---|---|---|"]
for t in ("CLAIM", "LISTING", "SCOPE", "DEF", "PAPER", "META"):
    md.append(f"| {t} | " + " | ".join(str(cnt[(t, v)]) for v in ("MATCH", "OVERSTATES", "UNDERSTATES", "MISSING-LEAN", "NAME-ONLY")) + f" | {cnt[(t, '')]} |")
md.append("")
order = sorted(byrung, key=lambda r: (r == "GENERAL", r))
for rung in order:
    rs = [r for r in byrung[rung] if r["type"] in JUDGED]
    if not rs: continue
    md += [f"## {rung}", "", "| loc | type | verdict | prose (tail) | Lean | literal statement | hidden hypotheses / note |", "|---|---|---|---|---|---|---|"]
    for r in rs:
        cell = lambda s, n=260: esc(s)[:n].replace("|", "\\|")
        lean = ", ".join(f"`{d.removeprefix('PositiveGeometryEmergentSpaceTime.')}`" for d in r["decls"][:6]) + (" …" if len(r["decls"]) > 6 else "")
        md.append(f"| {r['loc']} | {r['type']} | **{r['verdict']}** | {cell(r['prose'], 220)} | {lean} | {cell(r['lit'], 320)} | {cell((r['hid'] + ' — ' if r['hid'] else '') + r['note'], 360)} |")
    rw = [r for r in rs if r["rw"]]
    for r in rw: md.append(f"\n> **Proposed rewording ({r['loc']}):** {r['rw']}")
    md.append("")
(NOTES / "BLUEPRINT-ALL.md").write_text("\n".join(md) + "\n")

# ---------- GLOSSARY.md
loc = {x["term"]: x for x in glossary_terms.locate()}
gl = ["# Glossary of terms, symbols and Lean definitions the papers rely on (2026-11-03)", "",
      "Status: DEFINED = defined in words where the papers use it; MISSING-IN-PAPER = used without a definition in at least one paper that relies on it;",
      "MISMATCH = the paper's object differs from the Lean object. First use = first line matching the term in each paper (I, II, C).", "",
      "| term | plain-language definition (graduate level) | Lean def + literal statement | first use | status | note / proposed edit |", "|---|---|---|---|---|---|"]
st = collections.Counter()
for term, key, plain, defs, status, note in G:
    st[status] += 1
    lean = []
    for d in defs:
        if d.startswith("mod:"): lean.append(f"`{d[4:]}.*`"); continue
        n = "PositiveGeometryEmergentSpaceTime." + d
        if n not in I: lean.append(f"`{d}` (not in index)"); continue
        lit = def_literal(n, 4) if I[n]["kind"] in ("def", "structure", "abbrev") else sig(n, 200)
        lean.append(f"`{d}`: {esc(lit)[:220]}")
    h = loc.get(key, {}).get("hits", {})
    fu = "; ".join(f"{p}:{h[p][0]} ({h[p][1]})" for p in ("I", "II", "C") if p in h)
    gl.append("| " + " | ".join(x.replace("|", "\\|") for x in [term, plain, "<br>".join(lean) or "—", fu or "—", f"**{status}**", note]) + " |")
gl += ["", "Status counts: " + ", ".join(f"{k} {v}" for k, v in sorted(st.items())), ""]
(NOTES / "GLOSSARY.md").write_text("\n".join(gl) + "\n")

# ---------- batched check file
cited = sorted({d for r in rows if r["type"] in JUDGED for d in r["decls"]} | {"PositiveGeometryEmergentSpaceTime." + d for _, _, _, ds, _, _ in G for d in ds if not d.startswith("mod:") and "PositiveGeometryEmergentSpaceTime." + d in I})
alignment = [n for n in cited if ".Alignment." in I[n]["module"]]
mods = sorted({I[n]["module"] for n in alignment})
lean = ["import PositiveGeometryEmergentSpaceTime"] + [f"import {m}" for m in mods] + ["", "-- Generated by tools/alignment/build.py: existence + axioms of every cited declaration."]
for n in cited: lean.append(f"#print axioms {n}")
(OUT / "BlueprintCheck.lean").write_text("\n".join(lean) + "\n")
(OUT / "cited_all.txt").write_text("\n".join(cited) + "\n")
json.dump(dict(rows=len(rows), counts={f"{a}|{b}": c for (a, b), c in cnt.items()}, glossary=st, cited=len(cited)), open(OUT / "build_summary.json", "w"), indent=1, default=dict)
print("rows", len(rows), "cited", len(cited), "alignment mods", mods)
for (t, v), c in sorted(cnt.items()): print(t, v or "-", c)
print("glossary", dict(st))
