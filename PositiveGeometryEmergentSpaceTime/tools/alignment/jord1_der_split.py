"""Split the generated lean/.../Jord1Der.lean (tools/alignment/jord1_der_gen.py) into kernel-sized modules:
Jord1DerData (data + checkers), Jord1DerPeel (chunked peeling certificate), Jord1DerB0..B3 (13 basis
derivation checks each) and Jord1Der (assembly: finrank = 52). Run after jord1_der_gen.py."""
import re
ROOT = '<local path>'
S = f'{ROOT}/lean/PositiveGeometryEmergentSpaceTime/Alignment/Sanity'
src = open(f'{S}/Jord1Der.lean').read()
if 'import PositiveGeometryEmergentSpaceTime.Alignment.Sanity.Jord1DerPeel' in src:
    raise SystemExit('Jord1Der.lean is already the assembly; rerun jord1_der_gen.py first')
HDR_END = src.index('namespace PositiveGeometryEmergentSpaceTime.Alignment.Sanity.Jord1Der')
OPEN = ('namespace PositiveGeometryEmergentSpaceTime.Alignment.Sanity.Jord1Der\nopen Matrix PositiveGeometryEmergentSpaceTime.Jord1 PositiveGeometryEmergentSpaceTime.LeanCert PositiveGeometryEmergentSpaceTime.LeanCert2 '
        'PositiveGeometryEmergentSpaceTime.Alignment.Sanity.Jord1Sanity\n  PositiveGeometryEmergentSpaceTime.Alignment.Sanity.Jord1Bridge\n')
END = '\nend PositiveGeometryEmergentSpaceTime.Alignment.Sanity.Jord1Der\n'
def hdr(what, imports):
    return (f'/-\nCopyright (c) 2026 Savan Chhaniyara. All rights reserved.\nReleased under MIT license as described in the file LICENSE.\n'
            f'Authors: Savan Chhaniyara\n\nALIGNMENT PHASE C (2026-11-03) — JORD-1: {what}\n'
            'GENERATED by tools/alignment/jord1_der_gen.py + jord1_der_split.py. Not part of `import PositiveGeometryEmergentSpaceTime`.\n-/\n'
            + ''.join(f'import {i}\n' for i in imports) +
            '\nset_option autoImplicit false\nset_option maxHeartbeats 0\nset_option maxRecDepth 100000\n\n')

# 1. Data
cut = src.index('/-- The peeling certificate passes')
data = src[:cut].replace('JORD-1: `dim_ℚ Der(h3(O)) = 52`.', 'JORD-1: data and checkers for `dim_ℚ Der(h3(O)) = 52` (assembly in `Jord1Der`).') + END
open(f'{S}/Jord1DerData.lean', 'w').write(data)

# 2. Peel (chunked)
C, NCH, NCOV = 25, 28, 9
peel = hdr('chunked peeling certificate (upper bound `dim Der ≤ 52`).', ['PositiveGeometryEmergentSpaceTime.Alignment.Sanity.Jord1DerData']) + OPEN + f'''
/-! The single `decide +kernel` on `peelOK Fr steps` exhausted memory; here the same certificate is
checked in {NCH} chunks of {C} steps and the final coverage in {NCOV} blocks of 81 entries, each its own declaration. -/

/-- Target entry of a peeling step. -/
def tgt (s : ℕ × ℕ × ℕ × ℕ) : ℕ := s.2.2.2

/-- Chunk checker: like `peelOK` but without the final coverage test. -/
def peelC : List ℕ → List (ℕ × ℕ × ℕ × ℕ) → Bool
  | _, [] => true
  | known, (i, j, k, u) :: rest =>
    decide (i < 27) && decide (j < 27) && decide (k < 27) && (coefS (rowS i j k) u != 0) &&
      (rowS i j k).all (fun p => p.1 == u || known.contains p.1) && peelC (u :: known) rest

/-- Soundness of a chunk: every target of the chunk vanishes. -/
theorem peelC_sound (D : Mat) (hD : IsDer D) : ∀ (known : List ℕ) (st : List (ℕ × ℕ × ℕ × ℕ)),
    peelC known st = true → (∀ v ∈ known, Dv D v = 0) → ∀ v ∈ st.map tgt, Dv D v = 0
  | known, [], _, _ => by simp
  | known, (i, j, k, u) :: rest, h, hk => by
    simp only [peelC, Bool.and_eq_true, decide_eq_true_eq, bne_iff_ne, ne_eq, List.all_eq_true,
      Bool.or_eq_true, beq_iff_eq, List.contains_iff_mem] at h
    obtain ⟨⟨⟨⟨⟨hi, hj⟩, hk'⟩, hc⟩, hall⟩, hrest⟩ := h
    have hz : Dv D u = 0 := by
      have e : rv D (rowS i j k) = 0 := rv_rowS D hD ⟨i, hi⟩ ⟨j, hj⟩ ⟨k, hk'⟩
      rw [rv_single D _ u (fun p hp hne => hk _ ((hall p hp).resolve_left hne))] at e
      exact (mul_eq_zero.mp e).resolve_left (by exact_mod_cast hc)
    have ih := peelC_sound D hD (u :: known) rest hrest (by
      intro v hv
      rcases List.mem_cons.mp hv with rfl | hv
      · exact hz
      · exact hk v hv)
    intro v hv
    simp only [List.map_cons, List.mem_cons, tgt] at hv
    rcases hv with rfl | hv
    · exact hz
    · exact ih v hv

/-- Entries known after `m` chunks. -/
def knownOf (m : ℕ) : List ℕ := Fr ++ (steps.take (m * {C})).map tgt
/-- Chunk `m` of the peeling steps. -/
def chunkOf (m : ℕ) : List (ℕ × ℕ × ℕ × ℕ) := (steps.drop (m * {C})).take {C}

theorem knownOf_succ (m : ℕ) : knownOf (m + 1) = knownOf m ++ (chunkOf m).map tgt := by
  simp only [knownOf, chunkOf, Nat.succ_mul, List.take_add, List.map_append, List.append_assoc]

''' + ''.join(f'/-- Peeling chunk {m} (kernel). -/\ntheorem chunk_{m} : peelC (knownOf {m}) (chunkOf {m}) = true := by decide +kernel\n' for m in range(NCH)) + f'''
theorem chunks_all : ∀ m < {NCH}, peelC (knownOf m) (chunkOf m) = true := by
  intro m hm
  interval_cases m
''' + ''.join(f'  · exact chunk_{m}\n' for m in range(NCH)) + f'''
/-- Every entry known after `m ≤ {NCH}` chunks vanishes, given the `Fr` entries do. -/
theorem known_zero (D : Mat) (hD : IsDer D) (hF : ∀ v ∈ Fr, Dv D v = 0) :
    ∀ m ≤ {NCH}, ∀ v ∈ knownOf m, Dv D v = 0 := by
  intro m
  induction m with
  | zero => intro _ v hv; simp only [knownOf, Nat.zero_mul, List.take_zero, List.map_nil, List.append_nil] at hv; exact hF v hv
  | succ m ih =>
    intro hm v hv
    rw [knownOf_succ, List.mem_append] at hv
    rcases hv with hv | hv
    · exact ih (by omega) v hv
    · exact peelC_sound D hD _ _ (chunks_all m (by omega)) (ih (by omega)) v hv

''' + ''.join(f'/-- Coverage block {r} (kernel). -/\ntheorem cov_{r} : (List.range\' {81*r} 81).all (fun u => (knownOf {NCH}).contains u) = true := by decide +kernel\n' for r in range(NCOV)) + f'''
theorem cover (u : ℕ) (hu : u < 729) : u ∈ knownOf {NCH} := by
  have key : ∀ r < {NCOV}, (List.range' (81 * r) 81).all (fun u => (knownOf {NCH}).contains u) = true := by
    intro r hr
    interval_cases r
''' + ''.join(f'    · exact cov_{r}\n' for r in range(NCOV)) + f'''  have h := key (u / 81) (by omega)
  simp only [List.all_eq_true, List.mem_range', List.contains_iff_mem] at h
  exact h u ⟨u % 81, by omega, by omega⟩

/-- **Upper bound.** A derivation vanishing on the 52 entries `Fr` vanishes. -/
theorem peel_zero (D : Mat) (hD : IsDer D) (hF : ∀ v ∈ Fr, Dv D v = 0) : ∀ u < 729, Dv D u = 0 :=
  fun u hu => known_zero D hD hF {NCH} le_rfl u (cover u hu)

/-- `Fr` has 52 entries, all below 729. -/
theorem Fr_ok : Fr.length = 52 ∧ Fr.all (fun u => decide (u < 729)) = true := by decide +kernel

/-- Planted: chunk 1 does not pass from `Fr` alone (it needs chunk 0's entries). -/
theorem planted_chunk : peelC Fr (chunkOf 1) = false := by decide +kernel
''' + END
open(f'{S}/Jord1DerPeel.lean', 'w').write(peel)

# 3. Basis derivation checks
ders = re.findall(r'/-- Basis derivation (\d+) passes `derOK`\. -/\ntheorem der_\d+ : derOK \d+ = true := by decide \+kernel\n', src)
assert len(ders) == 52
for b in range(4):
    body = ''.join(f'/-- Basis derivation {t} passes `derOK` (kernel). -/\ntheorem der_{t} : derOK {t} = true := by decide +kernel\n'
                   for t in range(13 * b, 13 * b + 13))
    open(f'{S}/Jord1DerB{b}.lean', 'w').write(hdr(f'basis derivations {13*b}–{13*b+12} (lower bound).',
        ['PositiveGeometryEmergentSpaceTime.Alignment.Sanity.Jord1DerData']) + OPEN + '\n' + body + END)

# 4. Assembly
a0 = src.index('/-- All 52 basis checks. -/')
tail = src[a0:]
tail = tail.replace('have hall := peel_sound D.1 D.2 Fr steps peel_ok hF', 'have hall := peel_zero D.1 D.2 hF')
p0 = tail.index('/-- Planted: dropping the last peeling step')
tail = tail[:p0] + 'end PositiveGeometryEmergentSpaceTime.Alignment.Sanity.Jord1Der\n'
head = src[:HDR_END]
head = head.replace('import PositiveGeometryEmergentSpaceTime.Alignment.Sanity.Jord1Bridge\n', ''.join(f'import PositiveGeometryEmergentSpaceTime.Alignment.Sanity.{m}\n' for m in ['Jord1DerPeel', 'Jord1DerB0', 'Jord1DerB1', 'Jord1DerB2', 'Jord1DerB3']))
head = head.replace('(`peel_ok`, kernel-checked)', '(`Jord1DerPeel.peel_zero`, 28 kernel-checked chunks + 9 coverage blocks)')
head = head.replace('GENERATED by tools/alignment/jord1_der_gen.py (template tools/alignment/jord1_der_template.lean).',
                    'GENERATED by tools/alignment/jord1_der_gen.py + jord1_der_split.py (template jord1_der_template.lean).')
open(f'{S}/Jord1Der.lean', 'w').write(head + OPEN + '\n' + tail)
print('ok')
